export const t = text => locale === 'en' ? (english[text] ?? text) : text;
const originalText = new WeakMap(), originalAttrs = new WeakMap();
export function localize(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = []; while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(node => {
    if (node.parentElement?.closest('script,style,textarea,#library-grid,#draft-list,#rotating-word,#current-language,[data-locale],.social-rednote')) return;
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const original = originalText.get(node), key = original.trim();
    if (key && english[key]) node.nodeValue = original.replace(key, t(key));
  });
  root.querySelectorAll('[aria-label],[placeholder],[title],[alt]').forEach(element => {
    if (!originalAttrs.has(element)) originalAttrs.set(element, new Map());
    const originals = originalAttrs.get(element);
    ['aria-label','placeholder','title','alt'].forEach(name => {
      if (!element.hasAttribute(name)) return;
      if (!originals.has(name)) originals.set(name, element.getAttribute(name));
      const value = originals.get(name); element.setAttribute(name, t(value));
    });
  });
  document.documentElement.lang = locale;
  document.title = t('DOTTY — 从一个点子，到下一部作品');
  document.querySelector('meta[name=description]')?.setAttribute('content', t('DOTTY，为专业影视创作团队打造的 AI 创作工作流。'));
}
